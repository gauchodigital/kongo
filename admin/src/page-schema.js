export function youtubeId(value) {
  const raw = String(value || '').trim();
  const match = raw.match(/(?:youtu\.be\/|youtube(?:-nocookie)?\.com\/(?:watch\?v=|embed\/|shorts\/)|[?&]v=)([A-Za-z0-9_-]{6,})/)
    || raw.match(/^([A-Za-z0-9_-]{11})$/);
  return match ? match[1] : '';
}
